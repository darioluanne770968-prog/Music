// 威胁检测
export interface ThreatDetection {
  id: string;
  userId: string;
  enabled: boolean;
  alerts: ThreatAlert[];
  blockedThreats: BlockedThreat[];
  riskScore: number;
  lastScan: Date;
  settings: ThreatDetectionSettings;
}

export interface ThreatAlert {
  id: string;
  type: ThreatType;
  severity: 'low' | 'medium' | 'high' | 'critical';
  description: string;
  timestamp: Date;
  resolved: boolean;
  action: string;
  details: Record<string, any>;
}

export type ThreatType =
  | 'suspicious_login'
  | 'brute_force'
  | 'session_hijack'
  | 'phishing'
  | 'malware'
  | 'data_breach'
  | 'unauthorized_access'
  | 'account_takeover';

export interface BlockedThreat {
  id: string;
  type: ThreatType;
  source: string;
  blockedAt: Date;
  details: string;
}

export interface ThreatDetectionSettings {
  autoBlock: boolean;
  alertThreshold: 'low' | 'medium' | 'high';
  vpnDetection: boolean;
  geoBlocking: boolean;
  blockedCountries: string[];
  rateLimit: number;
  bruteForceProtection: boolean;
}
