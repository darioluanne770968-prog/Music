// 安全与隐私功能类型定义

// 端到端加密
export interface E2EEncryption {
  id: string;
  userId: string;
  enabled: boolean;
  keyPair: KeyPairInfo;
  encryptedData: EncryptedDataTypes;
  trustedDevices: TrustedDevice[];
  recoveryOptions: RecoveryOption[];
  auditLog: SecurityAuditEntry[];
}

export interface KeyPairInfo {
  publicKey: string;
  privateKeyHash: string;
  algorithm: 'RSA-4096' | 'ECDSA-P256' | 'Ed25519';
  createdAt: Date;
  expiresAt: Date;
  rotationReminder: boolean;
  lastRotation: Date;
}

export interface EncryptedDataTypes {
  playlists: boolean;
  listeningHistory: boolean;
  searchHistory: boolean;
  messages: boolean;
  downloads: boolean;
  preferences: boolean;
  paymentInfo: boolean;
}

export interface TrustedDevice {
  id: string;
  name: string;
  type: DeviceType;
  os: string;
  browser?: string;
  lastAccess: Date;
  firstAccess: Date;
  location: string;
  ipAddress: string;
  trusted: boolean;
  current: boolean;
  publicKey: string;
}

export type DeviceType = 'phone' | 'tablet' | 'desktop' | 'tv' | 'speaker' | 'car' | 'wearable';

export interface RecoveryOption {
  id: string;
  type: 'email' | 'phone' | 'recovery_key' | 'trusted_contact';
  value: string;
  verified: boolean;
  lastUsed?: Date;
}

export interface SecurityAuditEntry {
  id: string;
  timestamp: Date;
  action: SecurityAction;
  deviceId: string;
  ipAddress: string;
  location: string;
  success: boolean;
  details: string;
}

export type SecurityAction =
  | 'login'
  | 'logout'
  | 'password_change'
  | 'key_rotation'
  | 'device_added'
  | 'device_removed'
  | 'data_export'
  | 'data_delete'
  | 'permission_change';

// 匿名模式
